'use strict';

const { readFileSync, writeFileSync } = require('node:fs');
const { resolve, relative } = require('node:path');

const root = resolve(__dirname, '..');
const modelPath = resolve(root, 'model/security-capabilities.json');
const outputPath = resolve(root, 'docs/security-capability-model.md');

function normalizeEol(value) {
  return value.replace(/\r\n/g, '\n');
}

function inline(items) {
  return items.map(item => String(item).replaceAll('|', '\\|')).join('; ');
}

function linkList(links) {
  if (!links.length) return 'None yet.';
  return links.map(link => {
    const label = link.split('/').at(-1) || link;
    return `[${label}](${link.replaceAll(' ', '%20')})`;
  }).join(', ');
}

function renderCatalog(model) {
  const lines = [
    '<!-- GENERATED by scripts/render-capability-catalog.cjs from model/security-capabilities.json. Do not edit directly. -->',
    '',
    `# ${model.title}`,
    '',
    model.mission,
    '',
    `> **Current-state warning:** ${model.currentState}`,
    '',
    '## At a glance',
    '',
    '| Group | Capability | Maturity | Availability | Roadmap |',
    '| --- | --- | --- | --- | --- |'
  ];

  for (const group of model.groups) {
    for (const capability of model.capabilities.filter(item => item.group === group.id)) {
      lines.push(`| ${group.name} | [${capability.name}](#${capability.id}) | \`${capability.status}\` | \`${capability.actionability}\` | Phase ${capability.roadmapPhase} |`);
    }
  }

  lines.push(
    '',
    'No maturity status is an ecosystem-wide compliance claim. `IMPLEMENTED` means the Shield-owned artifact exists for its stated scope; only dated, attributable evidence can support `VERIFIED`.',
    '',
    '## Authority boundary',
    '',
    '**The Shield owns:**',
    '',
    ...model.authority.owns.map(item => `- ${item}`),
    '',
    '**The Shield does not own:**',
    '',
    ...model.authority.doesNotOwn.map(item => `- ${item}`),
    '',
    '## Production authorization invariant',
    '',
    `> **${model.productionAuthorization.invariant}**`,
    '',
    model.productionAuthorization.rule,
    '',
    model.productionAuthorization.prohibitedInference,
    '',
    '## Maturity and availability semantics',
    '',
    '| Status | Meaning |',
    '| --- | --- |',
    ...Object.entries(model.statusModel).map(([status, meaning]) => `| \`${status}\` | ${meaning} |`),
    '',
    '| Availability | Meaning |',
    '| --- | --- |',
    ...Object.entries(model.actionabilityModel).map(([status, meaning]) => `| \`${status}\` | ${meaning} |`),
    '',
    'Assessment results use `PASS`, `FAIL`, `BLOCKED`, `NOT TESTED`, and `TECHNICALLY UNAVAILABLE`. An absent assessment or absent evidence is never `PASS`.',
    '',
    '## Capability landscape'
  );

  for (const group of model.groups) {
    lines.push('', `## ${group.name}`, '', group.purpose);
    for (const capability of model.capabilities.filter(item => item.group === group.id)) {
      lines.push(
        '',
        `<a id="${capability.id}"></a>`,
        `### ${capability.name}`,
        '',
        `**${capability.status} · ${capability.actionability} · Phase ${capability.roadmapPhase}**`,
        '',
        capability.purpose,
        '',
        `- **Scope:** ${capability.scope}`,
        `- **Key sub-capabilities:** ${inline(capability.subCapabilities)}.`,
        `- **Expected policies:** ${inline(capability.expectedPolicies)}.`,
        `- **Expected standards:** ${inline(capability.expectedStandards)}.`,
        `- **Expected controls:** ${inline(capability.expectedControls)}.`,
        `- **Expected evidence:** ${inline(capability.expectedEvidence)}.`,
        `- **Dependencies:** ${capability.dependencies.length ? inline(capability.dependencies) : 'None recorded'}.`,
        `- **Future automation:** ${inline(capability.futureAutomation)}.`,
        `- **Repository links:** ${linkList(capability.links)}`
      );
    }
  }

  lines.push('', '## Progressive roadmap');
  for (const phase of model.roadmapPhases) {
    lines.push('', `### Phase ${phase.id} — ${phase.name}`, '', ...phase.outcomes.map(item => `- ${item}`));
  }

  lines.push(
    '',
    '## Cross-Ecosystem integration boundaries',
    '',
    '| System | Provides | Relationship to the Shield |',
    '| --- | --- | --- |',
    ...model.integrationBoundaries.map(boundary => `| ${boundary.name} | ${boundary.provides} | ${boundary.shieldRelationship} |`),
    '',
    'The Shield consumes references and scoped evidence from these systems. It does not copy their canonical inventories, live secrets, populated configuration, or application-specific evidence into this repository.',
    ''
  );

  return lines.join('\n');
}

function main() {
  const model = JSON.parse(readFileSync(modelPath, 'utf8'));
  const output = renderCatalog(model);
  if (process.argv.includes('--check')) {
    const actual = readFileSync(outputPath, 'utf8');
    if (normalizeEol(actual) !== normalizeEol(output)) {
      console.error(`${relative(root, outputPath)} is stale; run node scripts/render-capability-catalog.cjs`);
      process.exitCode = 1;
    }
    return;
  }
  writeFileSync(outputPath, output, 'utf8');
  console.log(`Rendered ${model.capabilities.length} capabilities to ${relative(root, outputPath)}.`);
}

if (require.main === module) main();

module.exports = { normalizeEol, renderCatalog };
