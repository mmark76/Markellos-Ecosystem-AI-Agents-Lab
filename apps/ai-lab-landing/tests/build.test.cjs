const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { existsSync, readFileSync, rmSync } = require('node:fs');
const { join, resolve } = require('node:path');
const test = require('node:test');

const app = resolve(__dirname, '..');
const output = join(app, 'dist');
const releaseVersion = readFileSync(join(app, '..', 'local-ai-agents-lab', 'VERSION'), 'utf8').trim();
const escapedReleaseVersion = releaseVersion.replaceAll('.', '\\.');

test('build creates a self-contained Pages artifact with a populated build ID', () => {
  rmSync(output, { recursive: true, force: true });
  execFileSync(process.execPath, ['build.cjs'], { cwd: app, stdio: 'pipe' });
  const html = readFileSync(join(output, 'index.html'), 'utf8');
  assert.match(html, new RegExp(`v${escapedReleaseVersion}_\\d{8}_\\d{4}_[0-9a-f]{7}`));
  assert.doesNotMatch(html, /\{\{BUILD_ID\}\}/);
  assert.match(html, /https:\/\/www\.python\.org\/downloads\/windows\//);
  assert.match(html, /https:\/\/ollama\.com\/download/);
  assert.match(html, /https:\/\/lmstudio\.ai\/download/);
  assert.match(html, /https:\/\/docs\.vllm\.ai\/en\/latest\/getting_started\/quickstart\//);
  assert.match(html, /not a native Windows desktop download/);
  assert.match(html, /href="http:\/\/127\.0\.0\.1:8765\/"/);
  assert.match(html, /Open Local Lab/);
  assert.equal((html.match(/Open Local Lab/g) || []).length, 1);
  assert.doesNotMatch(html, /secondary-button" href="http:\/\/127\.0\.0\.1:8765\//);
  assert.match(html, /data-color-mode="dark"/);
  assert.doesNotMatch(html, /background-color|Background colour/);
  assert.match(html, /Download AI-Agents-Lab-Windows\.zip/);
  assert.match(html, new RegExp(`Download AI-Agents-Lab-Windows\\.zip \\(v${escapedReleaseVersion}\\)`));
  assert.doesNotMatch(html, /\{\{RELEASE_VERSION\}\}/);
  assert.match(html, /FREE VERSION · SAFE · PRIVATE/);
  assert.match(html, /Train your AI agents on your own device\./);
  assert.match(html, /This public page is a guide only\. Download the ZIP to enter the Lab\./);
  assert.doesNotMatch(html, /The Lab, its models, and its conversation history are never hosted here\./);
  assert.doesNotMatch(html, /Free local use\. No subscription or API fees for the local Lab\./);
  assert.doesNotMatch(html, /Learn with AI agents, on your own device\./);
  assert.match(html, /id="zip-update" class="zip-update" type="button" hidden>New version available — Download ZIP/);
  assert.match(html, /Simple Guide/);
  assert.match(html, /href="\.\/simple-guide\.html" target="_blank" rel="noopener noreferrer"/);
  assert.doesNotMatch(html, /data-language|language-selector|language-button/);
  assert.match(html, /Only after the local server has started/);
  assert.match(html, /start-windows.bat/);
  assert.match(html, /There is no hidden installation folder/);
  assert.match(html, /this extracted folder is the Lab/);
  assert.match(html, /Desktop shortcut/);
  assert.match(html, /cannot start the Lab by itself/);
  assert.match(html, /Manual updates — important/);
  assert.match(html, /You do not download the ZIP each time you start the Lab/);
  assert.match(html, /data\/campus\.sqlite3/);
  assert.match(html, /class="site-header"/);
  assert.match(html, /class="primary-nav"/);
  assert.match(html, /href="#privacy"/);
  assert.match(html, /class="footer-inner"/);
  assert.match(html, /<script src="\.\/dashboard\.js"><\/script>/);
  assert.doesNotMatch(html, /Lab Assistant|assistant-button|assistant-dialog/);
  assert.match(html, /id="settings-dialog"/);
  assert.match(html, /id="info-dialog"/);
  for (const file of ['styles.css', 'tokens.css', 'dashboard.js', '_headers', 'README.md', 'simple-guide.html']) assert.equal(existsSync(join(output, file)), true, `${file} is missing`);
  assert.match(readFileSync(join(output, 'README.md'), 'utf8'), /# Markellos Ecosystem AI Agents Lab/);
  assert.match(readFileSync(join(output, 'simple-guide.html'), 'utf8'), /Start using AI Agents Lab/);
  assert.match(readFileSync(join(output, 'simple-guide.html'), 'utf8'), /Get started in six steps/);
  assert.match(readFileSync(join(output, '_headers'), 'utf8'), /connect-src 'self'/);
  assert.match(readFileSync(join(output, '_headers'), 'utf8'), /script-src 'self'/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /colorMode:'dark'/);
  assert.match(readFileSync(join(output, 'styles.css'), 'utf8'), /--color-background:#000000/);
  assert.doesNotMatch(readFileSync(join(output, 'styles.css'), 'utf8'), /--user-background/);
  assert.match(readFileSync(join(output, 'styles.css'), 'utf8'), /html\[data-color-mode="light"\].*--color-text:#172033/s);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /colorMode === 'dark' \? 'Light' : 'Dark'/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /checkForZipUpdate/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /scheduleZipUpdateChecks/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /window\.setInterval\(check, 60_000\)/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /document\.visibilityState === 'visible'/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /window\.fetch\(window\.location\.href, \{cache:'no-store'\}\)/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /isNewerRelease\(availableVersion, currentVersion\)/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /New version available: v\$\{availableVersion\.join\('\.'\)\} — Download ZIP/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /return available\[index\] > current\[index\];/);
  assert.match(readFileSync(join(output, 'dashboard.js'), 'utf8'), /zipUpdate\.addEventListener\('click',\(\)=>window\.location\.assign\(LATEST_ZIP_URL\)\)/);
  assert.match(readFileSync(join(output, 'styles.css'), 'utf8'), /\.zip-update \{ position: fixed;/);
});
